/* ---------- 轉成題庫格式（與 data/questions.js 相同欄位），供錯題本、練習題、老師專區查詢 ---------- */
var SELF_CHECK_QS = (function(){
  var out = [], k = 0;
  Object.keys(SELF_CHECK).forEach(function(card){
    var c = SELF_CHECK[card];
    c.qs.forEach(function(x, i){
      // 固定方式打散選項位置（每次載入都一樣，題號對應不會亂）
      var n = x.o.length, shift = (k * 3 + 1) % n, opts = [];
      for(var j = 0; j < n; j++) opts.push(x.o[(j + n - shift) % n]);
      out.push({ id:card + '-q' + (i + 1), unit:card.slice(0, 3), type:'single', level:1, card:card,
        question:x.q, options:opts, answer:shift, explain:x.e, bingo:'', tags:c.tags.concat(['概念卡檢核']), src:'概念卡自我檢核' });
      k++;
    });
  });
  return out;
})();
function selfCheckOf(card){ return SELF_CHECK_QS.filter(function(q){ return q.card === card; }); }

/* 有載入 questions.js 的頁面：讓 QB 也查得到這些題目（不會混進一般練習題與遊戲） */
(function(){
  if(typeof QB === 'undefined') return;
  var byId0 = QB.byId, filter0 = QB.filter;
  QB.byId = function(id){
    var q = byId0.call(QB, id); if(q) return q;
    for(var i = 0; i < SELF_CHECK_QS.length; i++){ if(SELF_CHECK_QS[i].id === id) return SELF_CHECK_QS[i]; }
    return null;
  };
  QB.filter = function(opt){
    var r = filter0.call(QB, opt);
    if(opt && opt.ids){
      r = r.concat(SELF_CHECK_QS.filter(function(q){
        if(opt.ids.indexOf(q.id) < 0) return false;
        if(opt.units && opt.units.length && opt.units.indexOf(q.unit) < 0) return false;
        if(opt.types && opt.types.length && opt.types.indexOf(q.type) < 0) return false;
        return true;
      }));
    }
    return r;
  };
})();
